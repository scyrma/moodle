/**
 * Create default custom fields.
 *
 * @return bool
 */
function xmldb_appointment_install() {
    if (!defined('BEHAT_SITE_RUNNING') && !(defined('PHPUNIT_TEST') && PHPUNIT_TEST)) {
        appointment_create_customfields(['location', 'venue', 'room']);
    }

    return true;
}
